"""Reproducible public-parameter fingerprints for the POSIX 48-bit LCG.

The native top-bit scan exhausts every hidden state for each declared trace.
LLL/CVP is a discovery heuristic: its failure is not a no-state proof. Separate
short-dual interval certificates prove exact exclusions with an independent
standard-library-only checker. Every match is replayed by integer recurrence.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from functools import lru_cache
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import time

MODULUS = 1 << 48
MULTIPLIER = 0x5DEECE66D
INCREMENT = 11
P521_GX = int(
    "00c6858e06b70404e9cd9e3ecb662395b4429c648139053fb521f828af606b4d3dbaa"
    "14b5e77efe75928fe1dc127a2ffa8de3348b3c1856a429bf97e7e31c2e5bd66", 16)
P521_GY = int(
    "011839296a789a3bc0045c8a5fb42c7d1bd998f54449579b446817afbd17273e662c"
    "97ee72995ef42640c550b9013fad0761353c7086a272c24088be94769fd16650", 16)
P521_SEED = bytes.fromhex("D09E8800291CB85396CC6717393284AAA0DA64BA")
P521_TIMESTAMP = 871002724


def step(state: int) -> int:
    return (MULTIPLIER * state + INCREMENT) % MODULUS


def previous(state: int) -> int:
    return ((state - INCREMENT) * pow(MULTIPLIER, -1, MODULUS)) % MODULUS


def outputs(first_state: int, count: int, bits: int) -> list[int]:
    """The first output observes first_state, then the recurrence advances."""
    if not 1 <= bits <= 48 or count < 0:
        raise ValueError("invalid output shape")
    state, result = first_state, []
    for _ in range(count):
        result.append(state >> (48 - bits))
        state = step(state)
    return result


def candidate_seed(timestamp: int, candidate: int) -> bytes:
    if not 0 <= timestamp < (1 << 32) or candidate < 1:
        raise ValueError("timestamp or candidate outside the declared range")
    state = (timestamp << 16) | 0x330E
    result = bytearray()
    for i in range(20 * candidate):
        state = step(state)
        if i >= 20 * (candidate - 1):
            result.append(state >> 40)
    return bytes(result)


def recover_top_bits_python(words: list[int], bits: int) -> list[int]:
    """Exhaustive reference checker, suitable for a few controls."""
    if not 28 <= bits <= 48 or len(words) < 3:
        raise ValueError("require at least three observations and 28..48 bits")
    if any(not 0 <= word < (1 << bits) for word in words):
        raise ValueError("observation exceeds the output width")
    hidden = 48 - bits
    base = words[0] << hidden
    return [base | low for low in range(1 << hidden)
            if outputs(base | low, len(words), bits) == words]


def recover_top_bytes_lattice(data: bytes) -> list[int]:
    """Return replay-verified CVP candidate states; no completeness claim.

    Put x_i = a^i x_0 + d_i mod 2^48. The lattice generated by
    (1,a,...,a^(n-1)) and 2^48*e_i (i>0) contains the untruncated
    coordinates after removing d_i. CVP targets interval midpoints.
    """
    if len(data) < 8:
        raise ValueError("at least eight bytes required")
    try:
        from fpylll import CVP, IntegerMatrix, LLL
    except ImportError as exc:
        raise RuntimeError("optional dependency fpylll (and cysignals) required") from exc
    n = len(data)
    rows = [[0] * n for _ in range(n)]
    rows[0] = [pow(MULTIPLIER, i, MODULUS) for i in range(n)]
    for i in range(1, n):
        rows[i][i] = MODULUS
    lattice = IntegerMatrix.from_matrix(rows)
    LLL.reduction(lattice)
    d, target = 0, []
    for byte in data:
        target.append((byte << 40) + (1 << 39) - d)
        d = step(d)
    vector = CVP.closest_vector(lattice, target)
    state = int(vector[0]) % MODULUS
    return [state] if outputs(state, n, 8) == list(data) else []


@lru_cache(maxsize=8)
def _short_dual_relations(count: int) -> tuple[tuple[int, ...], ...]:
    """Discover exact annihilating rows; LLL is outside certificate checking."""
    try:
        from fpylll import IntegerMatrix, LLL
    except ImportError as exc:
        raise RuntimeError("optional dependency fpylll required for discovery") from exc
    rows = [[0] * count for _ in range(count)]
    rows[0][0] = MODULUS
    for i in range(1, count):
        rows[i][0] = -pow(MULTIPLIER, i, MODULUS)
        rows[i][i] = 1
    matrix = IntegerMatrix.from_matrix(rows)
    LLL.reduction(matrix)
    relations = [tuple(int(matrix[i, j]) for j in range(count)) for i in range(count)]
    return tuple(sorted(relations, key=lambda row: sum(map(abs, row))))


def exclusion_certificate(data: bytes) -> dict | None:
    """Find a dual interval that contains no multiple of 2^48.

    If z_i = x_i-d_i, every compatible state obeys sum(v_i*z_i)=0 mod M
    whenever sum(v_i*a^i)=0 mod M. Observed top bytes bound each z_i.
    A resulting interval missing all multiples of M is an exact contradiction.
    """
    for row in _short_dual_relations(len(data)):
        d, base = 0, 0
        for coefficient, byte in zip(row, data):
            base += coefficient * ((byte << 40) - d)
            d = step(d)
        lower = base + sum(min(0, coefficient) for coefficient in row) * ((1 << 40) - 1)
        upper = base + sum(max(0, coefficient) for coefficient in row) * ((1 << 40) - 1)
        if -(-lower // MODULUS) > upper // MODULUS:
            certificate = {"schema": "perfectjet/lcg-dual-exclusion/1",
                           "observation_hex": data.hex(), "coefficients": list(row),
                           "interval_lower": lower, "interval_upper": upper}
            if not verify_exclusion(certificate):
                raise ValueError("discovered certificate failed independent checking")
            return certificate
    return None


def verify_exclusion(certificate: dict) -> bool:
    """Standard-library-only, exact verifier; does not call LLL or CVP."""
    try:
        if certificate["schema"] != "perfectjet/lcg-dual-exclusion/1":
            return False
        data = bytes.fromhex(certificate["observation_hex"])
        row = certificate["coefficients"]
        if not data or len(data) != len(row) or any(type(v) is not int for v in row):
            return False
        if sum(v * pow(MULTIPLIER, i, MODULUS) for i, v in enumerate(row)) % MODULUS:
            return False
        lower = upper = 0
        offset = 0
        for value, coefficient in zip(data, row):
            lo = value * (1 << 40) - offset
            hi = (value + 1) * (1 << 40) - 1 - offset
            lower += coefficient * (lo if coefficient >= 0 else hi)
            upper += coefficient * (hi if coefficient >= 0 else lo)
            offset = (MULTIPLIER * offset + INCREMENT) % MODULUS
        return (lower == certificate["interval_lower"] and
                upper == certificate["interval_upper"] and
                -(-lower // MODULUS) > upper // MODULUS)
    except (KeyError, TypeError, ValueError):
        return False


def byte_assembly_exclusions(min_bytes: int = 65, max_bytes: int = 110) -> dict:
    """Exclude complete direct-byte assembly families using Mersenne windows.

    For R=G+qP, P=2^521-1, one has R=G-q+q*2^521. A window below bit521
    remains unchanged if G modulo its lower power of two is at least every
    admissible q. Such an interior output trace has an independently checked
    no-state certificate. The raw integer may have either output-byte order.
    """
    certificates, uncovered = [], []
    p = (1 << 521) - 1
    for name, coordinate in [("Gx", P521_GX), ("Gy", P521_GY)]:
        for count in range(min_bytes, max_bytes + 1):
            maximum_raw = (1 << (8 * count)) - 1
            if maximum_raw < coordinate:
                certificates.append({"coordinate": name, "raw_bytes": count,
                                     "reason": "raw_range_below_coordinate"})
                continue
            qmax = (maximum_raw - coordinate) // p
            candidates = []
            for low in range(0, 521 - 160 + 1, 8):
                if low + 160 > 8 * count:
                    continue
                if coordinate % (1 << low) < qmax:
                    continue
                blob = ((coordinate >> low) & ((1 << 160) - 1)).to_bytes(20, "big")
                pair = [exclusion_certificate(blob), exclusion_certificate(blob[::-1])]
                if all(pair):
                    candidates = [
                        {"schema": "perfectjet/p521-byte-assembly-exclusion/1",
                         "coordinate": name, "raw_bytes": count, "byte_order": order,
                         "window_low_bit": low, "maximum_quotient": qmax,
                         "dual_certificate": certificate}
                        for order, certificate in zip(["big", "little"], pair)]
                    break
            if candidates:
                if not all(verify_byte_assembly_exclusion(c) for c in candidates):
                    raise ValueError("complete assembly certificate failed replay")
                certificates.extend(candidates)
            else:
                uncovered.append({"coordinate": name, "raw_bytes": count})
    return {"method": "Mersenne-interior-window-dual-exclusion",
            "min_raw_bytes": min_bytes, "max_raw_bytes": max_bytes,
            "certificates": certificates, "uncovered": uncovered,
            "scope": "Direct consecutive top-eight-bit LCG bytes, big/little assembly and reduction modulo 2^521-1. Every certificate excludes all 48-bit states and every admissible reduction quotient. Other output slices, discarded bytes, hashing, scalar multiplication and other generators remain outside this model."}


def verify_byte_assembly_exclusion(certificate: dict) -> bool:
    """Exact checker for the Mersenne carry bound plus dual obstruction."""
    try:
        if certificate["schema"] != "perfectjet/p521-byte-assembly-exclusion/1":
            return False
        coordinate = {"Gx": P521_GX, "Gy": P521_GY}[certificate["coordinate"]]
        count, low = certificate["raw_bytes"], certificate["window_low_bit"]
        if type(count) is not int or type(low) is not int or not 1 <= count <= 1024:
            return False
        if low < 0 or low % 8 or low + 160 > min(521, 8 * count):
            return False
        qmax = (((1 << (8 * count)) - 1) - coordinate) // ((1 << 521) - 1)
        if qmax < 0 or certificate["maximum_quotient"] != qmax:
            return False
        if coordinate % (1 << low) < qmax:
            return False
        blob = ((coordinate >> low) & ((1 << 160) - 1)).to_bytes(20, "big")
        if certificate["byte_order"] == "little":
            blob = blob[::-1]
        elif certificate["byte_order"] != "big":
            return False
        dual = certificate["dual_certificate"]
        return dual["observation_hex"] == blob.hex() and verify_exclusion(dual)
    except (KeyError, TypeError, ValueError):
        return False


def timestamp_ancestors(first_state: int, max_steps: int = 200_000) -> list[dict]:
    """Enumerate all srand48-shaped ancestors in the stated finite depth."""
    result, state = [], first_state
    for distance in range(max_steps + 1):
        if (state & 0xFFFF) == 0x330E:
            timestamp = state >> 16
            result.append({"distance_before_first_output": distance,
                           "timestamp": timestamp,
                           "utc": datetime.fromtimestamp(timestamp, timezone.utc).isoformat()})
        state = previous(state)
    return result


def coordinate_queries(observations: int = 4) -> list[dict]:
    """Every bit-aligned trace in both byte orders of each 66-byte coordinate.

    Modes are contiguous top31, contiguous top32, and top31 padded to32.
    This checks fingerprints, without asserting a full coordinate assembly.
    """
    result = []
    for coordinate_name, coordinate in [("Gx", P521_GX), ("Gy", P521_GY)]:
        encoded = coordinate.to_bytes(66, "big")
        for byte_order, blob in [("big", encoded), ("reversed", encoded[::-1])]:
            bitstring = "".join(f"{byte:08b}" for byte in blob)
            for bits, stride, pad in [(31, 31, 0), (32, 32, 0), (31, 32, 1)]:
                for offset in range(len(bitstring) - observations * stride + 1):
                    chunks = [bitstring[offset + j * stride:offset + (j + 1) * stride]
                              for j in range(observations)]
                    if pad and any(chunk[0] != "0" for chunk in chunks):
                        continue
                    words = [int(chunk[pad:], 2) for chunk in chunks]
                    result.append({"coordinate": coordinate_name, "byte_order": byte_order,
                                   "output_bits": bits, "stride": stride,
                                   "bit_offset": offset, "words": words})
    return result


def scan_top_bits(native_binary: str | Path | None = None) -> dict:
    queries = coordinate_queries()
    controls = []
    for bits in [31, 32]:
        state = step((P521_TIMESTAMP << 16) | 0x330E)
        controls.append({"coordinate": "synthetic-control", "byte_order": "big",
                         "output_bits": bits, "stride": bits, "bit_offset": 0,
                         "words": outputs(state, 6, bits), "expected_state": state})
    all_queries = queries + controls
    payload = "".join(f"{q['output_bits']} {len(q['words'])} " +
                      " ".join(map(str, q["words"])) + "\n" for q in all_queries)
    with tempfile.TemporaryDirectory(prefix="p521-lcg-") as temporary:
        binary = Path(native_binary) if native_binary else Path(temporary) / "lcg_scan"
        if native_binary is None:
            source = Path(__file__).with_name("lcg_scan.cpp")
            subprocess.run(["c++", "-O3", "-std=c++17", str(source), "-o", str(binary)], check=True)
        process = subprocess.run([str(binary)], input=payload, text=True,
                                 capture_output=True, check=True)
    lines = process.stdout.splitlines()
    if len(lines) != len(all_queries):
        raise ValueError("native scanner returned wrong number of results")
    matches, control_results = [], []
    for query, line in zip(all_queries, lines):
        values = list(map(int, line.split()))
        if not values or values[0] != len(values) - 1:
            raise ValueError("invalid scanner result")
        states = values[1:]
        if any(outputs(s, len(query["words"]), query["output_bits"]) != query["words"]
               for s in states):
            raise ValueError("native candidate failed independent recurrence replay")
        if "expected_state" in query:
            if states != [query["expected_state"]]:
                raise ValueError("positive control failed")
            control_results.append({**query, "states": states, "passed": True})
        elif states:
            matches.append({**query, "states": states})
    return {"method": "exhaustive-top-bit-fingerprints", "observations_per_trace": 4,
            "traces": len(queries),
            "states_enumerated": sum(1 << (48 - q["output_bits"]) for q in queries),
            "query_sha256": hashlib.sha256(payload.encode()).hexdigest(),
            "matches": matches, "controls": control_results,
            "scope": "All hidden states for the declared traces; no universal coordinate-generation exclusion."}


def scan_top_bytes() -> dict:
    controls = recover_top_bytes_lattice(P521_SEED)
    if len(controls) != 1:
        raise ValueError("known P521 seed inverse positive control failed")
    ancestors = timestamp_ancestors(controls[0], 25_000)
    expected = {"timestamp": P521_TIMESTAMP, "distance_before_first_output": 20 * 1135 + 1}
    if not any(all(a[k] == v for k, v in expected.items()) for a in ancestors):
        raise ValueError("known P521 initialization was not recovered")
    matches, queries, certificates = [], 0, []
    for name, value in [("Gx", P521_GX), ("Gy", P521_GY)]:
        blob = value.to_bytes(66, "big")
        for order, data in [("big", blob), ("reversed", blob[::-1])]:
            for offset in range(len(data) - 20 + 1):
                queries += 1
                states = recover_top_bytes_lattice(data[offset:offset + 20])
                if states:
                    matches.append({"coordinate": name, "byte_order": order,
                                    "byte_offset": offset, "states": states})
                certificate = exclusion_certificate(data[offset:offset + 20])
                if certificate:
                    certificates.append({"coordinate": name, "byte_order": order,
                                         "byte_offset": offset, "certificate": certificate})
    return {"method": "LLL-CVP-top-byte-fingerprints", "traces": queries,
            "matches": matches,
            "positive_control": {"curve": "P-521", "first_state": controls[0],
                                 "timestamp": P521_TIMESTAMP, "candidate": 1136,
                                 "recovered_initialization": expected},
            "exactly_excluded_traces": len(certificates),
            "dual_exclusion_certificates": certificates,
            "scope": "CVP is heuristic. Each dual certificate excludes all 2^48 hidden states for its exact 20-byte trace. No universal coordinate-generation exclusion."}


def verify_report(report: dict) -> dict:
    """Replay proof-bearing receipt parts without a compiler or dependencies."""
    if report.get("schema") != "perfectjet/p521-lcg-forensics/1":
        raise ValueError("unsupported receipt schema")
    if report.get("seed_forward_control") != candidate_seed(P521_TIMESTAMP, 1136).hex().upper():
        raise ValueError("seed forward control mismatch")
    rows = report["top_bytes"]["dual_exclusion_certificates"]
    expected = {}
    for name, coordinate in [("Gx", P521_GX), ("Gy", P521_GY)]:
        blob = coordinate.to_bytes(66, "big")
        for order, data in [("big", blob), ("reversed", blob[::-1])]:
            for offset in range(47):
                expected[name, order, offset] = data[offset:offset + 20].hex()
    seen = set()
    for row in rows:
        key = row["coordinate"], row["byte_order"], row["byte_offset"]
        if key in seen or key not in expected:
            raise ValueError("duplicate or unexpected dual trace")
        seen.add(key)
        certificate = row["certificate"]
        if certificate["observation_hex"] != expected[key] or not verify_exclusion(certificate):
            raise ValueError("invalid dual trace proof")
    if seen != set(expected):
        raise ValueError("dual trace coverage is incomplete")
    if report["top_bytes"]["exactly_excluded_traces"] != len(expected):
        raise ValueError("wrong dual trace count")
    assembly_seen = set()
    assembly = report["byte_assembly"]
    # This release freezes the experiment domain: changing it needs a new
    # schema rather than a receipt which silently shrinks its proof coverage.
    if assembly["min_raw_bytes"] != 65 or assembly["max_raw_bytes"] != 110:
        raise ValueError("wrong byte-assembly experiment domain")
    assembly_expected = set()
    for name, coordinate in [("Gx", P521_GX), ("Gy", P521_GY)]:
        for count in range(65, 110):
            if (1 << (8 * count)) - 1 < coordinate:
                assembly_expected.add((name, count, "range"))
            else:
                assembly_expected.update([(name, count, "big"), (name, count, "little")])
    uncovered = assembly["uncovered"]
    if (len(uncovered) != 2 or
            {(row["coordinate"], row["raw_bytes"]) for row in uncovered} !=
            {("Gx", 110), ("Gy", 110)}):
        raise ValueError("wrong uncovered model domain")
    for certificate in assembly["certificates"]:
        if certificate.get("reason") == "raw_range_below_coordinate":
            coordinate = {"Gx": P521_GX, "Gy": P521_GY}[certificate["coordinate"]]
            count = certificate["raw_bytes"]
            if not 1 <= count <= 1024 or (1 << (8 * count)) - 1 >= coordinate:
                raise ValueError("invalid raw-range exclusion")
            key = certificate["coordinate"], count, "range"
        else:
            if not verify_byte_assembly_exclusion(certificate):
                raise ValueError("invalid complete byte-assembly proof")
            key = certificate["coordinate"], certificate["raw_bytes"], certificate["byte_order"]
        if key in assembly_seen:
            raise ValueError("duplicate assembly proof")
        assembly_seen.add(key)
    if assembly_seen != assembly_expected:
        raise ValueError("complete byte-assembly proof coverage mismatch")
    return {"verified": True, "dual_trace_proofs": len(seen),
            "byte_assembly_proofs": len(assembly_seen),
            "native_scan": "Not rerun by this certificate-only checker"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write deterministic JSON (no wall-clock fields)")
    parser.add_argument("--with-lattice", action="store_true",
                        help="also discover exact byte/assembly exclusions and inverse control; requires fpylll")
    parser.add_argument("--timing", action="store_true", help="print runtime to stderr, outside the receipt")
    parser.add_argument("--verify", type=Path,
                        help="verify retained exact certificates with the standard library only")
    args = parser.parse_args()
    if args.verify:
        print(json.dumps(verify_report(json.loads(args.verify.read_text())), indent=2))
        return
    started = time.perf_counter()
    result = {"schema": "perfectjet/p521-lcg-forensics/1",
              "seed_forward_control": candidate_seed(P521_TIMESTAMP, 1136).hex().upper(),
              "top_bits": scan_top_bits()}
    if result["seed_forward_control"] != P521_SEED.hex().upper():
        raise ValueError("forward seed replay failed")
    if args.with_lattice:
        result["top_bytes"] = scan_top_bytes()
        result["byte_assembly"] = byte_assembly_exclusions()
    rendered = json.dumps(result, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered)
    print(rendered)
    if args.timing:
        print(f"Elapsed seconds: {time.perf_counter() - started:.6f}", file=sys.stderr)


if __name__ == "__main__":
    main()
