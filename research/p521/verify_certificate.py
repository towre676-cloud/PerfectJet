"""Independent, standard-library-only verifier for the P-521 FreeLIP exclusions.

This module imports no discovery, lattice-reduction, or elliptic-curve module.
It checks an integer modular separator, not the correctness of an LLL solver.
Its target and arithmetic constants are fixed by the public research contract.
"""
from __future__ import annotations

import argparse
from itertools import product
import json
from pathlib import Path
import sys

MODULUS = (1 << 107) - 1
MULTIPLIER = pow(3, 121, MODULUS)
RADIX = 1 << 26
FIELD = (1 << 521) - 1
TARGET = int(
    'c6858e06b70404e9cd9e3ecb662395b4429c648139053fb521f828af606b4d3d'
    'baa14b5e77efe75928fe1dc127a2ffa8de3348b3c1856a429bf97e7e31c2e5bd66', 16)


class CertificateError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise CertificateError(message)


def integers(values):
    return isinstance(values, list) and all(type(v) is int for v in values)


def forced_outputs(count, order):
    """Derive the necessary output trace directly from the published Gx.

    Write an assembled value as H*2^521+L. Reduction modulo 2^521-1
    implies H+L=Gx or Gx+p. For these three layouts the fixed target is
    farther from either endpoint than H can reach, so L=Gx-H. Its low
    26*first bits cannot borrow, leaving all selected full limbs fixed.
    """
    require(type(count) is int and count in (20, 21, 22), 'unsupported limb count')
    require(order in ('msb', 'lsb'), 'unsupported limb order')
    if count == 20:
        require(TARGET < 1 << 520, '20-limb target does not fit')
        first, last, start = 0, 19, 0
    else:
        h = 26*count-521
        high_limit = (1 << h)-1
        first, last = (h+25)//26, 19
        require(high_limit < TARGET < FIELD-high_limit,
                'target requires additional modular wrap cases')
        require(TARGET % (1 << (26*first)) >= high_limit,
                'target requires additional subtraction carry cases')
        start = count-1-last if order == 'msb' else first
    indexes = list(range(first, last+1))
    if order == 'msb':
        indexes.reverse()
    outputs = [(TARGET >> (26*k)) & (RADIX-1) for k in indexes]
    return {'outputs': outputs, 'first_output_index': start,
            'lowest_limb': first, 'highest_limb': last,
            'prefix': TARGET >> (26*first)}


def dual_bounds(outputs, numerator, denominator, gaps=None):
    """Check a dual congruence and bound its value over every hidden-state box.

    If x_i=y_i+B*u_i are consecutive states, their high parts satisfy
    u_i=A^i*u_0+d_i (mod M), d_i=(A^i*y_0-y_i)/B (mod M).
    Thus u-d lies in the row lattice generated by (1,A,...,A^(s-1))
    and M*e_i for i>0. The dual dot product must be divisible by D.
    """
    require(integers(outputs) and len(outputs) >= 2 and
            all(0 <= y < RADIX for y in outputs), 'invalid observed outputs')
    require(integers(numerator) and len(numerator) == len(outputs),
            'invalid dual numerator')
    require(type(denominator) is int and denominator > 0,
            'invalid dual denominator')
    gaps = [1]*(len(outputs)-1) if gaps is None else gaps
    require(integers(gaps) and len(gaps) == len(outputs)-1 and
            all(g in (1, 2) for g in gaps), 'invalid raw recurrence gaps')
    powers, exponent = [1], 0
    for gap in gaps:
        exponent += gap
        powers.append(pow(MULTIPLIER, exponent, MODULUS))
    require(sum(a*q for a, q in zip(powers, numerator)) % denominator == 0,
            'dual functional is not integral on the power row')
    require(all(MODULUS*q % denominator == 0 for q in numerator[1:]),
            'dual functional is not integral on modular rows')
    inverse_radix = pow(RADIX, -1, MODULUS)
    minimum = maximum = 0
    for a, y, q in zip(powers, outputs, numerator):
        shift = ((a*outputs[0]-y)*inverse_radix) % MODULUS
        upper = (MODULUS-1-y)//RADIX
        endpoint0, endpoint1 = -q*shift, q*(upper-shift)
        minimum += min(endpoint0, endpoint1)
        maximum += max(endpoint0, endpoint1)
    first_multiple = -((-minimum)//denominator)
    last_multiple = maximum//denominator
    return {'minimum': minimum, 'maximum': maximum,
            'first_multiple_index': first_multiple,
            'last_multiple_index': last_multiple,
            'excludes_every_state': first_multiple > last_multiple}


def quotient_contradiction(outputs, numerator, gaps):
    """Second proof: bound k=sum(q_i*x_i)/M and its forced residue modulo B."""
    exponent, relation = 0, numerator[0]
    for q, gap in zip(numerator[1:], gaps):
        exponent += gap
        relation += q*pow(MULTIPLIER, exponent, MODULUS)
    require(relation % MODULUS == 0, 'quotient relation fails modulo M')
    low_sum = (MODULUS-1)*sum(q for q in numerator if q < 0)
    high_sum = (MODULUS-1)*sum(q for q in numerator if q > 0)
    low, high = -((-low_sum)//MODULUS), high_sum//MODULUS
    residue = -sum(q*y for q, y in zip(numerator, outputs)) % RADIX
    first = low+(residue-low) % RADIX
    require(first > high, 'quotient bounds contain the required residue')
    return {'quotient_minimum': low, 'quotient_maximum': high,
            'quotient_residue_modulo_2_26': residue,
            'first_compatible_quotient': first}


def verify_dual(certificate, expected_outputs, source_rejection=False):
    require(isinstance(certificate, dict), 'dual certificate must be an object')
    require(certificate.get('schema') == 'perfectjet/freelip-dual-exclusion/1',
            'wrong dual certificate schema')
    require(certificate.get('outputs') == expected_outputs,
            'certificate observations differ from public target')
    gaps = certificate.get('gaps', [1]*(len(expected_outputs)-1))
    result = dual_bounds(expected_outputs, certificate.get('numerator'),
                         certificate.get('denominator'), gaps)
    require(source_rejection or all(g == 1 for g in gaps),
            'nonconsecutive outputs in no-rejection model')
    require(type(certificate.get('minimum')) is int and
            certificate['minimum'] == result['minimum'], 'incorrect lower bound')
    require(type(certificate.get('maximum')) is int and
            certificate['maximum'] == result['maximum'], 'incorrect upper bound')
    require(result['excludes_every_state'], 'dual interval contains a lattice multiple')
    if certificate['denominator'] == MODULUS:
        result.update(quotient_contradiction(expected_outputs, certificate['numerator'], gaps))
    result['gaps'] = gaps
    return result


def verify_rejection_gap(proof):
    require(isinstance(proof, dict) and
            proof.get('schema') == 'perfectjet/freelip-rejection-gap/1',
            'missing source rejection-gap proof')
    q = proof.get('numerator')
    require(integers(q) and len(q) == 2 and all(v > 0 for v in q),
            'invalid rejection-gap numerator')
    require(proof.get('denominator') == MODULUS and
            (q[0]+MULTIPLIER*q[1]) % MODULUS == 0,
            'invalid rejection-gap modular relation')
    low, high = sum(q), (RADIX-1)*sum(q)
    require(0 < low <= high < MODULUS, 'rejection interval contains a modular multiple')
    require(proof.get('reject_distance_minimum') == 1 and
            proof.get('reject_distance_maximum') == RADIX-1 and
            proof.get('minimum') == low and proof.get('maximum') == high,
            'incorrect rejection-gap bounds')
    # Rejected raw states are M-r with 1<=r<=B-1. Two consecutive rejected
    # states would force q0*r+q1*s to be a positive multiple of M below M.
    return True


def verify_document(document):
    require(isinstance(document, dict) and
            document.get('schema') == 'perfectjet/freelip-recovery-suite/1',
            'wrong research receipt schema')
    profiles = document.get('profiles')
    require(isinstance(profiles, list) and len(profiles) == 6, 'need all six profiles')
    source_rejection = document.get('source_rejection', False)
    require(type(source_rejection) is bool, 'invalid source-rejection contract')
    verified, seen = [], set()
    for profile in profiles:
        require(isinstance(profile, dict), 'profile must be an object')
        require(profile.get('schema') == 'perfectjet/freelip-coordinate-recovery/1',
                'wrong profile schema')
        count, order = profile.get('limb_count'), profile.get('order')
        expected = forced_outputs(count, order)
        identity = (count, order)
        require(identity not in seen, 'duplicate assembly profile')
        seen.add(identity)
        require(profile.get('target') == hex(TARGET), 'wrong target coordinate')
        require(profile.get('complete') is True and profile.get('candidates') == [],
                'profile does not claim complete exclusion')
        require(profile.get('source_rejection', False) is source_rejection,
                'profile disagrees with suite rejection model')
        if source_rejection:
            verify_rejection_gap(profile.get('rejection_gap_proof'))
        branches = profile.get('branches')
        require(isinstance(branches, list) and branches, 'missing output-gap branches')
        seen_gaps, observation_count, sample_bounds = set(), None, None
        for branch in branches:
            require(isinstance(branch, dict) and branch.get('interior') == expected,
                    'incorrect forced coordinate window')
            used = branch.get('observations_used')
            require(type(used) is int and 2 <= used <= len(expected['outputs']),
                    'invalid observation count')
            require(observation_count is None or observation_count == used,
                    'gap branches use inconsistent observation counts')
            observation_count = used
            recovery = branch.get('recovery')
            require(isinstance(recovery, dict) and recovery.get('status') == 'excluded'
                    and recovery.get('complete') is True and recovery.get('states') == [],
                    'branch lacks a complete dual exclusion')
            bounds = verify_dual(recovery.get('certificate'), expected['outputs'][:used], source_rejection)
            pattern = tuple(bounds['gaps'])
            require(pattern not in seen_gaps, 'duplicate output-gap branch')
            seen_gaps.add(pattern)
            if sample_bounds is None:
                sample_bounds = bounds
        gap_domain = (1, 2) if source_rejection else (1,)
        require(seen_gaps == set(product(gap_domain, repeat=observation_count-1)),
                'output-gap coverage is incomplete')
        verified.append({'limb_count': count, 'order': order,
                         'observations_used': observation_count,
                         'gap_patterns_verified': len(seen_gaps),
                         'sample_certificate': sample_bounds})
    require(seen == {(n, o) for n in (20, 21, 22) for o in ('msb', 'lsb')},
            'assembly profile coverage is incomplete')
    return {'verified': True, 'source_rejection': source_rejection, 'profiles': verified,
            'scope': 'All states modulo 2^107-1 for the fixed FreeLIP multiplier, '
                     'low26 output, listed assemblies, and final field reduction; '
                     + ('including the source rejection loop.' if source_rejection else
                        'consecutive raw draws with no rejection loop.'),
            'synthetic_recovery_controls': 'Checked by the separate discovery tests; '
                                           'not inferred from receipt summary flags.'}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('receipt', nargs='?', type=Path,
                        default=Path(__file__).with_name('results')/'freelip-source-recovery.json')
    args = parser.parse_args(argv)
    try:
        result = verify_document(json.loads(args.receipt.read_text(encoding='utf-8')))
    except (CertificateError, OSError, json.JSONDecodeError, KeyError, TypeError) as exc:
        print(f'Certificate rejected: {exc}', file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
